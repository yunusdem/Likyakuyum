IF OBJECT_ID('dbo.TODVZ_STOK_FIYAT_LISTESI', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_STOK_FIYAT_LISTESI (
    FIYAT_LISTESI_ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_TODVZ_STOK_FIYAT_LISTESI PRIMARY KEY,
    AD NVARCHAR(100) NOT NULL,
    AKTIF BIT NOT NULL CONSTRAINT DF_TODVZ_STOK_FIYAT_LISTESI_AKTIF DEFAULT 1,
    SIRA INT NOT NULL CONSTRAINT DF_TODVZ_STOK_FIYAT_LISTESI_SIRA DEFAULT 0,
    EKLEYEN_ID INT NULL,
    EKLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_STOK_FIYAT_LISTESI_EZ DEFAULT GETDATE(),
    CONSTRAINT UQ_TODVZ_STOK_FIYAT_LISTESI_AD UNIQUE (AD)
  );
END;
GO

-- Kart × liste fiyatı (kartın para birimi ve KDV dahil işaretine uyar); satır yoksa ana fiyat (TODVZ_STOK_KART.SATIS_FIYATI)
IF OBJECT_ID('dbo.TODVZ_STOK_KART_FIYAT', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_STOK_KART_FIYAT (
    STOK_KART_ID INT NOT NULL,
    FIYAT_LISTESI_ID INT NOT NULL,
    FIYAT FLOAT NOT NULL,
    GUNCELLEYEN_ID INT NULL,
    GUNCELLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_STOK_KART_FIYAT_GZ DEFAULT GETDATE(),
    CONSTRAINT PK_TODVZ_STOK_KART_FIYAT PRIMARY KEY (STOK_KART_ID, FIYAT_LISTESI_ID)
  );
  CREATE NONCLUSTERED INDEX IX_TODVZ_STOK_KART_FIYAT_LISTE ON dbo.TODVZ_STOK_KART_FIYAT (FIYAT_LISTESI_ID);
END;
GO

-- Tedarikçi (son giriş fişindeki cari ya da kartta elle)
IF OBJECT_ID('dbo.TODVZ_STOK_KART', 'U') IS NOT NULL AND COL_LENGTH('dbo.TODVZ_STOK_KART', 'TEDARIKCI_CARI_ID') IS NULL
BEGIN
  ALTER TABLE dbo.TODVZ_STOK_KART ADD TEDARIKCI_CARI_ID INT NULL;
END;
GO
IF OBJECT_ID('dbo.TODVZ_STOK_KART', 'U') IS NOT NULL AND NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_TODVZ_STOK_KART_TEDARIKCI' AND object_id = OBJECT_ID('dbo.TODVZ_STOK_KART'))
  CREATE NONCLUSTERED INDEX IX_TODVZ_STOK_KART_TEDARIKCI ON dbo.TODVZ_STOK_KART (TEDARIKCI_CARI_ID);
GO

-- Cari → varsayılan fiyat listesi
IF OBJECT_ID('dbo.TODVZ_STOK_CARI_FIYAT_LISTESI', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_STOK_CARI_FIYAT_LISTESI (
    CARI_KART_ID INT NOT NULL CONSTRAINT PK_TODVZ_STOK_CARI_FIYAT_LISTESI PRIMARY KEY,
    FIYAT_LISTESI_ID INT NOT NULL,
    GUNCELLEYEN_ID INT NULL,
    GUNCELLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_STOK_CARI_FIYAT_LISTESI_GZ DEFAULT GETDATE()
  );
END;
GO

-- Toplu fiyat işlemi geçmişi (geri alma için eski → yeni)
IF OBJECT_ID('dbo.TODVZ_STOK_FIYAT_GECMISI', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_STOK_FIYAT_GECMISI (
    GECMIS_ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_TODVZ_STOK_FIYAT_GECMISI PRIMARY KEY,
    ISLEM_NO INT NOT NULL,
    STOK_KART_ID INT NOT NULL,
    FIYAT_LISTESI_ID INT NULL,          -- NULL: ana satış fiyatı
    ALAN VARCHAR(10) NOT NULL,          -- SATIS / ALIS
    ESKI_FIYAT FLOAT NULL,
    YENI_FIYAT FLOAT NULL,
    TARIH DATETIME NOT NULL CONSTRAINT DF_TODVZ_STOK_FIYAT_GECMISI_T DEFAULT GETDATE(),
    KULLANICI_ID INT NULL,
    ACIKLAMA NVARCHAR(300) NULL,
    GERI_ALINDI BIT NOT NULL CONSTRAINT DF_TODVZ_STOK_FIYAT_GECMISI_GA DEFAULT 0
  );
  CREATE NONCLUSTERED INDEX IX_TODVZ_STOK_FIYAT_GECMISI_ISLEM ON dbo.TODVZ_STOK_FIYAT_GECMISI (ISLEM_NO);
END;
GO

-- Kampanya: tarihli yüzde / tutar indirimi; hedef gruplar / kartlar / tümü. Satışta satır iskontosu olarak uygulanır.
IF OBJECT_ID('dbo.TODVZ_STOK_KAMPANYA', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_STOK_KAMPANYA (
    KAMPANYA_ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_TODVZ_STOK_KAMPANYA PRIMARY KEY,
    AD NVARCHAR(100) NOT NULL,
    BASLANGIC DATETIME NOT NULL,
    BITIS DATETIME NOT NULL,
    TUR TINYINT NOT NULL,               -- 1 yüzde, 2 tutar (satır birim fiyatından, KDV dahil)
    DEGER FLOAT NOT NULL,
    HEDEF_TURU TINYINT NOT NULL,        -- 1 gruplar, 2 kartlar, 3 tümü
    AKTIF BIT NOT NULL CONSTRAINT DF_TODVZ_STOK_KAMPANYA_AKTIF DEFAULT 1,
    ACIKLAMA NVARCHAR(300) NULL,
    EKLEYEN_ID INT NULL,
    EKLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_STOK_KAMPANYA_EZ DEFAULT GETDATE(),
    GUNCELLEYEN_ID INT NULL,
    GUNCELLEME_ZAMANI DATETIME NULL
  );
END;
GO
IF OBJECT_ID('dbo.TODVZ_STOK_KAMPANYA_HEDEF', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_STOK_KAMPANYA_HEDEF (
    KAMPANYA_HEDEF_ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_TODVZ_STOK_KAMPANYA_HEDEF PRIMARY KEY,
    KAMPANYA_ID INT NOT NULL,
    STOK_GRUP_ID INT NULL,
    STOK_KART_ID INT NULL
  );
  CREATE NONCLUSTERED INDEX IX_TODVZ_STOK_KAMPANYA_HEDEF_K ON dbo.TODVZ_STOK_KAMPANYA_HEDEF (KAMPANYA_ID);
END;
GO

-- Fişe liste ve satıra kampanya izi
IF OBJECT_ID('dbo.TODVZ_FATURA', 'U') IS NOT NULL AND COL_LENGTH('dbo.TODVZ_FATURA', 'FIYAT_LISTESI_ID') IS NULL
  ALTER TABLE dbo.TODVZ_FATURA ADD FIYAT_LISTESI_ID INT NULL;
GO
IF OBJECT_ID('dbo.TODVZ_FATURA_SATIRI', 'U') IS NOT NULL AND COL_LENGTH('dbo.TODVZ_FATURA_SATIRI', 'KAMPANYA_ID') IS NULL
  ALTER TABLE dbo.TODVZ_FATURA_SATIRI ADD KAMPANYA_ID INT NULL;
GO
