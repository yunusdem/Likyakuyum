-- Hızlı Satış (docs/HIZLI_SATIS_YOL_HARITASI.md, H1–H21)
-- Buton düzeni firma bazında (modül → sekme → buton), ayarlar (fatura sınırı), Fiyat/İndirim yetkisi ve
-- hızlı satıştan kaydedilen fişlerin işareti. Eski programın fiş tablolarına kolon eklenmez; işaret ayrı tabloda.
-- Tekrar çalıştırılabilir.

IF OBJECT_ID('dbo.TODVZ_HIZLI_SATIS_SEKME', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_HIZLI_SATIS_SEKME (
    SEKME_ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_TODVZ_HIZLI_SATIS_SEKME PRIMARY KEY,
    MODUL VARCHAR(20) NOT NULL,
    AD NVARCHAR(60) NOT NULL,
    SIRA INT NOT NULL CONSTRAINT DF_TODVZ_HIZLI_SATIS_SEKME_SIRA DEFAULT 0,
    EKLEYEN_ID INT NULL,
    EKLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_HIZLI_SATIS_SEKME_EZ DEFAULT GETDATE()
  );
  CREATE NONCLUSTERED INDEX IX_TODVZ_HIZLI_SATIS_SEKME_MODUL ON dbo.TODVZ_HIZLI_SATIS_SEKME (MODUL, SIRA);
END;
GO

-- URUN_TURU: 1 Ürün Tanımı / para birimi (TODVZ_PARA), 2 stok kartı (TODVZ_STOK_KART), 3 serbest ürün (ad + fiyat + KDV)
-- Resim TODVZ_URUN_RESIM'de TIP 4, ISLEM_ID = BUTON_ID (küçültülmüş); RESIM yalnız var/yok işareti.
IF OBJECT_ID('dbo.TODVZ_HIZLI_SATIS_BUTON', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_HIZLI_SATIS_BUTON (
    BUTON_ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_TODVZ_HIZLI_SATIS_BUTON PRIMARY KEY,
    SEKME_ID INT NOT NULL,
    SIRA INT NOT NULL CONSTRAINT DF_TODVZ_HIZLI_SATIS_BUTON_SIRA DEFAULT 0,
    URUN_TURU TINYINT NOT NULL,
    URUN_ID INT NULL,
    AD NVARCHAR(60) NULL,
    RENK VARCHAR(9) NULL,
    FIYAT FLOAT NULL,
    KDV_ORANI FLOAT NULL,
    RESIM BIT NOT NULL CONSTRAINT DF_TODVZ_HIZLI_SATIS_BUTON_RESIM DEFAULT 0,
    EKLEYEN_ID INT NULL,
    EKLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_HIZLI_SATIS_BUTON_EZ DEFAULT GETDATE()
  );
  CREATE NONCLUSTERED INDEX IX_TODVZ_HIZLI_SATIS_BUTON_SEKME ON dbo.TODVZ_HIZLI_SATIS_BUTON (SEKME_ID, SIRA);
END;
GO

-- Ayarlar (FATURA_SINIRI: 12.000 TL alıcı bilgisi sınırı, H12)
IF OBJECT_ID('dbo.TODVZ_HIZLI_SATIS_AYAR', 'U') IS NULL
  CREATE TABLE dbo.TODVZ_HIZLI_SATIS_AYAR (
    ANAHTAR VARCHAR(50) NOT NULL CONSTRAINT PK_TODVZ_HIZLI_SATIS_AYAR PRIMARY KEY,
    DEGER NVARCHAR(200) NULL
  );
GO

-- "Hızlı Satış – Fiyat/İndirim" yetkisi verilen kullanıcılar (H17; sistem yöneticisi her zaman yetkili)
IF OBJECT_ID('dbo.TODVZ_HIZLI_SATIS_YETKI', 'U') IS NULL
  CREATE TABLE dbo.TODVZ_HIZLI_SATIS_YETKI (
    KULLANICI_ID INT NOT NULL CONSTRAINT PK_TODVZ_HIZLI_SATIS_YETKI PRIMARY KEY,
    EKLEYEN_ID INT NULL,
    EKLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_HIZLI_SATIS_YETKI_EZ DEFAULT GETDATE()
  );
GO

-- Hızlı satıştan kaydedilen fişler (H20). MODUL: perakende / ticari (TODVZ_FATURA), sarraf (TODVZ_SARRAF_FISI), doviz (TODVZ_FIS)
IF OBJECT_ID('dbo.TODVZ_HIZLI_SATIS_FIS', 'U') IS NULL
  CREATE TABLE dbo.TODVZ_HIZLI_SATIS_FIS (
    MODUL VARCHAR(20) NOT NULL,
    FIS_ID INT NOT NULL,
    KULLANICI_ID INT NULL,
    EKLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_HIZLI_SATIS_FIS_EZ DEFAULT GETDATE(),
    CONSTRAINT PK_TODVZ_HIZLI_SATIS_FIS PRIMARY KEY CLUSTERED (MODUL, FIS_ID)
  );
GO
