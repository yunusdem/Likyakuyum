    SATICI_VKN VARCHAR(11) NOT NULL,
    ANAHTAR NVARCHAR(260) NOT NULL,
    STOK_KART_ID INT NOT NULL CONSTRAINT FK_TODVZ_STOK_EFATURA_ESLESME_KART REFERENCES dbo.TODVZ_STOK_KART (STOK_KART_ID),
    CARPAN DECIMAL(18,6) NOT NULL CONSTRAINT CK_TODVZ_STOK_EFATURA_ESLESME_CARPAN CHECK (CARPAN > 0),
    GUNCELLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_STOK_EFATURA_ESLESME_GZ DEFAULT GETDATE(),
    CONSTRAINT UQ_TODVZ_STOK_EFATURA_ESLESME UNIQUE (SATICI_VKN, ANAHTAR)
  );
  PRINT 'TODVZ_STOK_EFATURA_ESLESME tablosu kuruldu.';
