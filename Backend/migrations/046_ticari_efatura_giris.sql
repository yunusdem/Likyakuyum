IF OBJECT_ID('dbo.TODVZ_STOK_EFATURA_ALIM', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_STOK_EFATURA_ALIM (
    ALIM_ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_TODVZ_STOK_EFATURA_ALIM PRIMARY KEY,
    ETTN VARCHAR(40) NOT NULL CONSTRAINT UQ_TODVZ_STOK_EFATURA_ALIM_ETTN UNIQUE,
    FATURA_NO VARCHAR(30) NULL,
    SATICI_VKN VARCHAR(11) NULL,
    CARI_KART_ID INT NOT NULL,
    STOK_GIRIS_ID INT NOT NULL,
    FATURA_TUTARI DECIMAL(18,2) NULL,
    EKLEYEN_ID INT NULL,
    EKLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_STOK_EFATURA_ALIM_EZ DEFAULT GETDATE()
  );
  CREATE NONCLUSTERED INDEX IX_TODVZ_STOK_EFATURA_ALIM_GIRIS ON dbo.TODVZ_STOK_EFATURA_ALIM (STOK_GIRIS_ID);
  PRINT 'TODVZ_STOK_EFATURA_ALIM tablosu kuruldu.';
END
GO

IF OBJECT_ID('dbo.TODVZ_STOK_EFATURA_ESLESME', 'U') IS NULL
