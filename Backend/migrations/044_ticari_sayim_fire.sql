-- Göç 044: Ticari sayım fişi + fire / zayi fişi (docs/TICARI_ADISYON_YOL_HARITASI.md, TA11 / TA12)
--   TODVZ_STOK_SAYIM (+ _SATIR): sayım anı (TARIH), isteğe bağlı grup süzgeci; taslak (DURUM 0) → onay (DURUM 1).
--     Onayda her satırın sistem miktarı sayım anındaki bakiyedir (SISTEM yazılır); fark stok hareketi olur
--     (TODVZ_STOK_HAREKET.BELGE_TURU 3: fazla GİRİŞ, eksik ÇIKIŞ). Onay geri alınınca hareketler silinir, fiş taslağa döner.
--   TODVZ_STOK_FIRE (+ _SATIR): neden + miktar; stok düşer (BELGE_TURU 4, ÇIKIŞ), satıra o anki birim maliyet yazılır.
-- Yalnız ekleme; tekrar çalıştırılabilir. Uygulama da ilk kullanımda aynı dosyayı çalıştırır (ticariSema.ts).
-- ============================================================================

IF OBJECT_ID('dbo.TODVZ_STOK_SAYIM', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_STOK_SAYIM (
