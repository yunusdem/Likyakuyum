    DURUM TINYINT NOT NULL CONSTRAINT DF_TODVZ_STOK_SAYIM_DURUM DEFAULT 0 CONSTRAINT CK_TODVZ_STOK_SAYIM_DURUM CHECK (DURUM IN (0, 1)),
    EKLEYEN_ID INT NULL,
    EKLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_STOK_SAYIM_EZ DEFAULT GETDATE(),
    GUNCELLEYEN_ID INT NULL,
    GUNCELLEME_ZAMANI DATETIME NULL,
    ONAYLAYAN_ID INT NULL,
    ONAY_ZAMANI DATETIME NULL
  );
  PRINT 'TODVZ_STOK_SAYIM tablosu kuruldu.';
END
GO

IF OBJECT_ID('dbo.TODVZ_STOK_SAYIM_SATIR', 'U') IS NULL
