-- Tekrar çalıştırılabilir.

IF OBJECT_ID('dbo.TODVZ_KUR_KAYNAK_AYAR', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_KUR_KAYNAK_AYAR (
    AYAR_ID INT NOT NULL CONSTRAINT PK_TODVZ_KUR_KAYNAK_AYAR PRIMARY KEY CLUSTERED,
    KAYNAK VARCHAR(20) NOT NULL CONSTRAINT DF_TODVZ_KUR_KAYNAK_AYAR_KAYNAK DEFAULT 'tcmb',
    DEGISTIREN VARCHAR(100) NULL,
    DEGISIM_TARIHI DATETIME NOT NULL CONSTRAINT DF_TODVZ_KUR_KAYNAK_AYAR_TARIH DEFAULT GETDATE()
  );
END;
GO

IF OBJECT_ID('dbo.TODVZ_KUR_KOMISYON', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.TODVZ_KUR_KOMISYON (
    PARA_ID INT NOT NULL CONSTRAINT PK_TODVZ_KUR_KOMISYON PRIMARY KEY CLUSTERED,
    ALIS_TUR CHAR(1) NOT NULL CONSTRAINT DF_TODVZ_KUR_KOMISYON_ALIS_TUR DEFAULT 'T',
    ALIS_DEGER DECIMAL(18, 6) NOT NULL CONSTRAINT DF_TODVZ_KUR_KOMISYON_ALIS_DEGER DEFAULT 0,
    SATIS_TUR CHAR(1) NOT NULL CONSTRAINT DF_TODVZ_KUR_KOMISYON_SATIS_TUR DEFAULT 'T',
    SATIS_DEGER DECIMAL(18, 6) NOT NULL CONSTRAINT DF_TODVZ_KUR_KOMISYON_SATIS_DEGER DEFAULT 0,
    GUNCELLEME_ZAMANI DATETIME NOT NULL CONSTRAINT DF_TODVZ_KUR_KOMISYON_ZAMAN DEFAULT GETDATE()
  );
END;
GO
