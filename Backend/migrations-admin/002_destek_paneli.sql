/* LIKYA_ADMIN göçü 002 — Destek paneli (destek.likyakuyum.com): destek ekibi hesapları, oturumları, hızlı cevaplar,
   talep ataması / ilk cevap / kapatan personel kolonları (docs/DESTEK_PANELI_YOL_HARITASI.md).
   Tekrar çalıştırılabilir yazılır. Önkoşul: LIKYA_ADMIN_DESTEK.sql (ADM_KONU tabloları) kurulu olmalı. */
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO

IF OBJECT_ID('dbo.ADM_DESTEK_PERSONEL') IS NULL
BEGIN
  CREATE TABLE dbo.ADM_DESTEK_PERSONEL (
    PERSONEL_ID            INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    KULLANICI_ADI          NVARCHAR(50)  COLLATE Latin1_General_CI_AS NOT NULL,
    AD_SOYAD               NVARCHAR(100) NOT NULL,
    SIFRE_HASH             VARCHAR(100)  NULL,               -- admin paneli hesabına bağlıysa NULL (şifre ADM_ADMIN'den)
    SIFRE_DEGISMELI        BIT           NOT NULL DEFAULT 1,
    ROL                    VARCHAR(10)   NOT NULL DEFAULT 'PERSONEL', -- ADMIN | PERSONEL
    GORME                  VARCHAR(10)   NOT NULL DEFAULT 'TUMU',     -- TUMU | ATANAN
    DURUM                  VARCHAR(10)   NOT NULL DEFAULT 'AKTIF',    -- AKTIF | PASIF
    ADMIN_ID               INT           NULL,               -- doluysa admin paneli hesabı (her zaman destek admini)
    HATALI_DENEME          INT           NOT NULL DEFAULT 0,
    KILIT_BITIS            DATETIME      NULL,
    SON_GIRIS              DATETIME      NULL,
    OLUSTURAN_PERSONEL_ID  INT           NULL,
    OLUSTURMA_TARIHI       DATETIME      NOT NULL DEFAULT GETDATE(),
    CONSTRAINT UQ_ADM_DESTEK_PERSONEL_AD UNIQUE (KULLANICI_ADI),
    CONSTRAINT CK_ADM_DESTEK_PERSONEL_ROL CHECK (ROL IN ('ADMIN','PERSONEL')),
    CONSTRAINT CK_ADM_DESTEK_PERSONEL_GORME CHECK (GORME IN ('TUMU','ATANAN')),
    CONSTRAINT CK_ADM_DESTEK_PERSONEL_DURUM CHECK (DURUM IN ('AKTIF','PASIF'))
  );
END
GO

-- Bir admin hesabına en fazla bir personel satırı (süzgeçli dizin QUOTED_IDENTIFIER ON ister)
SET QUOTED_IDENTIFIER ON;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'UQ_ADM_DESTEK_PERSONEL_ADMIN')
  CREATE UNIQUE INDEX UQ_ADM_DESTEK_PERSONEL_ADMIN ON dbo.ADM_DESTEK_PERSONEL (ADMIN_ID) WHERE ADMIN_ID IS NOT NULL;
GO

IF OBJECT_ID('dbo.ADM_DESTEK_OTURUM') IS NULL
BEGIN
  CREATE TABLE dbo.ADM_DESTEK_OTURUM (
    OTURUM_ID     UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    PERSONEL_ID   INT           NOT NULL,
    IP            VARCHAR(64)   NULL,
    TARAYICI      NVARCHAR(400) NULL,
    BASLANGIC     DATETIME      NOT NULL DEFAULT GETDATE(),
    SON_ISLEM     DATETIME      NOT NULL DEFAULT GETDATE(),
    BITIS         DATETIME      NULL,
    IPTAL_EDILDI  BIT           NOT NULL DEFAULT 0
  );
  CREATE INDEX IX_ADM_DESTEK_OTURUM_PERSONEL ON dbo.ADM_DESTEK_OTURUM (PERSONEL_ID, BITIS);
END
GO

IF OBJECT_ID('dbo.ADM_DESTEK_HIZLI_CEVAP') IS NULL
BEGIN
  CREATE TABLE dbo.ADM_DESTEK_HIZLI_CEVAP (
    CEVAP_ID          INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    BASLIK            NVARCHAR(100)  NOT NULL,
    METIN             NVARCHAR(4000) NOT NULL,
    SIRA              INT            NOT NULL DEFAULT 0,
    AKTIF             BIT            NOT NULL DEFAULT 1,
    OLUSTURMA_TARIHI  DATETIME       NOT NULL DEFAULT GETDATE()
  );
END
GO

IF OBJECT_ID('dbo.ADM_KONU') IS NOT NULL AND COL_LENGTH('dbo.ADM_KONU', 'ATANAN_PERSONEL_ID') IS NULL
BEGIN
  ALTER TABLE dbo.ADM_KONU ADD
    ATANAN_PERSONEL_ID     INT          NULL,
    ATAMA_TARIHI           DATETIME     NULL,
    ILK_CEVAP_TARIHI       DATETIME     NULL,
    ILK_CEVAP_PERSONEL_ID  INT          NULL,
    KAPATAN_PERSONEL_ID    INT          NULL,
    OLUSTURAN_PERSONEL_ID  INT          NULL,
    KAYNAK                 VARCHAR(10)  NULL;   -- NULL/MUSTERI | TELEFON
END
GO

IF OBJECT_ID('dbo.ADM_KONU') IS NOT NULL AND NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_ADM_KONU_ATANAN_PERSONEL')
  CREATE INDEX IX_ADM_KONU_ATANAN_PERSONEL ON dbo.ADM_KONU (ATANAN_PERSONEL_ID, TUR, DURUM);
GO

IF OBJECT_ID('dbo.ADM_KONU_MESAJ') IS NOT NULL AND COL_LENGTH('dbo.ADM_KONU_MESAJ', 'PERSONEL_ID') IS NULL
  ALTER TABLE dbo.ADM_KONU_MESAJ ADD PERSONEL_ID INT NULL;
GO

-- Admin paneli adminleri destek panelinde destek admini sayılır: her birine bağlı personel satırı (ad çakışırsa atlanır)
INSERT INTO dbo.ADM_DESTEK_PERSONEL (KULLANICI_ADI, AD_SOYAD, SIFRE_HASH, SIFRE_DEGISMELI, ROL, GORME, DURUM, ADMIN_ID)
SELECT a.KULLANICI_ADI, a.AD_SOYAD, NULL, 0, 'ADMIN', 'TUMU', a.DURUM, a.ADMIN_ID
FROM dbo.ADM_ADMIN a
WHERE NOT EXISTS (SELECT 1 FROM dbo.ADM_DESTEK_PERSONEL p WHERE p.ADMIN_ID = a.ADMIN_ID)
  AND NOT EXISTS (SELECT 1 FROM dbo.ADM_DESTEK_PERSONEL p WHERE p.KULLANICI_ADI = a.KULLANICI_ADI);
GO

-- Eski atamalar (admin) personel satırına taşınır; geçmiş cevaplar için ilk cevap bilgisi doldurulur
IF OBJECT_ID('dbo.ADM_KONU') IS NOT NULL
BEGIN
  EXEC('
    UPDATE k SET ATANAN_PERSONEL_ID = p.PERSONEL_ID
    FROM dbo.ADM_KONU k INNER JOIN dbo.ADM_DESTEK_PERSONEL p ON p.ADMIN_ID = k.ATANAN_ADMIN_ID
    WHERE k.ATANAN_ADMIN_ID IS NOT NULL AND k.ATANAN_PERSONEL_ID IS NULL;

    UPDATE m SET PERSONEL_ID = p.PERSONEL_ID
    FROM dbo.ADM_KONU_MESAJ m INNER JOIN dbo.ADM_DESTEK_PERSONEL p ON p.ADMIN_ID = m.ADMIN_ID
    WHERE m.GONDEREN_TUR = ''ADMIN'' AND m.ADMIN_ID IS NOT NULL AND m.PERSONEL_ID IS NULL;

    UPDATE k SET ILK_CEVAP_TARIHI = x.TARIH, ILK_CEVAP_PERSONEL_ID = x.PERSONEL_ID
    FROM dbo.ADM_KONU k
    CROSS APPLY (SELECT TOP 1 m.TARIH, m.PERSONEL_ID FROM dbo.ADM_KONU_MESAJ m
                 WHERE m.KONU_ID = k.KONU_ID AND m.GONDEREN_TUR = ''ADMIN'' AND m.IC_NOT = 0 ORDER BY m.MESAJ_ID) x
    WHERE k.TUR = ''TALEP'' AND k.ILK_CEVAP_TARIHI IS NULL;
  ');
END
GO
