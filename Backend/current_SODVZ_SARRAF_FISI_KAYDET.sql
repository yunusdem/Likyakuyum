
CREATE OR ALTER PROCEDURE SODVZ_SARRAF_FISI_KAYDET
	@SARRAF_FISI_ID KAYIT_ID OUT,
	@VEZNE_ID KAYIT_ID,
	@CARI_KART_ID KAYIT_ID,
	@TARIH TARIH,
	@SAAT ZAMAN,
	@FIS_NO KOD OUT,
	@TIP TUR,
	@ALTIN_HAS_KURU KUR,
	@KDV_ORANI ORAN,
	@KDV MEBLAG,
	@E_FATURA_POSTA_KUTUSU TANIM_ADI,
	@E_IRSALIYE_POSTA_KUTUSU TANIM_ADI,
	@IRSALIYE_NO KOD OUT,
	@IRSALIYE_ZAMANI ZAMAN,
	@KISILIK_TIPI TUR,
	@UYRUK_ID KAYIT_ID,
	@ULKE_ID KAYIT_ID,
	@PASAPORT_NO KOD,
	@HUKUKI_YAPI_ID KAYIT_ID,
	@VERGI_DAIRESI_ID KAYIT_ID,
	@VERGI_KIMLIK_NO KOD,
	@BABA_ADI TANIM_ADI,
	@ADRES ACIKLAMA,
	@ILCE_ID KAYIT_ID,
	@POSTA_KODU_ID KAYIT_ID,
	@IL_ID KAYIT_ID,
	@VEKIL_TURU TUR,
	@VEKIL_KISILIK_TIPI TUR,
	@VEKIL_ADI TANIM_ADI,
	@VEKIL_KIMLIK_NO KOD,
	@EPOSTA ACIKLAMA,
	@TELEFON_NO TELEFON,
	@MESLEK_ID KAYIT_ID,
	@DOGUM_TARIHI TARIH,
	@DOGUM_YERI ACIKLAMA,
	@KIMLIK_SERI_NO KOD,
	@ANNE_ADI TANIM_ADI,
	@MASAK_LISTESINDE_VAR BOOL,
	@SUPHELI_ISLEMLER_YETKILI_ID KAYIT_ID,
	@YETKILI_KISI_ID KAYIT_ID,
	@SIRKET_TURU TUR,
	@KIMLIK_GECERLILIK_TARIHI TARIH,
	@KIMLIK_BELGE_TURU TUR,
	@DERNEK_AMACI TANIM_ADI,
	@YETKILI_KISI TANIM_ADI,
	@BELGE_TURU TUR,
	@SOFOR_ID KAYIT_ID,
	@UNVAN TANIM_ADI,
	@FAVORI_PARA_ID KAYIT_ID,
	@ALIS_KURU KUR,
	@SATIS_KURU KUR,
	@GUMUS_HAS_KURU KUR,
	@KULLANICI_ID KAYIT_ID,
	@GUID GUID = NULL,
	@DEGISIKLIK_TAKIP_VAR BOOL = 0,
	@YAZDIRILAN_BELGE_TIPI TUR = NULL,
	@YENI_KAYIT BOOL OUT
AS
BEGIN
	SET NOCOUNT ON
	DECLARE @HATA_MESAJI TANIM_ADI
	DECLARE @DONUS_KODU INT
	DECLARE @SIMDIKI_ZAMAN ZAMAN
	DECLARE @DONUS_DEGERI TAMSAYI
	DECLARE @NUMERATOR_TURU TUR
	DECLARE @ONEK KISA_AD
	DECLARE @ONUNE_SIFIR_KOY BOOL
	DECLARE @E_BELGE_AKTIF BOOL
	DECLARE @KAYITSIZ_MUSTERI_ID KAYIT_ID

	IF @CARI_KART_ID < 0
	BEGIN
		SET @KAYITSIZ_MUSTERI_ID = -@CARI_KART_ID
		SET @CARI_KART_ID = NULL
	END

	IF EXISTS(SELECT * FROM TODVZ_TANIM WHERE E_BELGE_BASLANGIC_TARIHI <= @TARIH) 
		SET @E_BELGE_AKTIF = 1
	ELSE 
		SET @E_BELGE_AKTIF = 0

	SET @SIMDIKI_ZAMAN = GETDATE()

	IF @GUID IS NOT NULL 
		SELECT @SARRAF_FISI_ID = SARRAF_FISI_ID FROM TODVZ_SARRAF_FISI WHERE GUID = @GUID

	IF (@SARRAF_FISI_ID IS NULL) 
		SET @YENI_KAYIT = 1
	ELSE 
		SET @YENI_KAYIT = 0

	IF @YAZDIRILAN_BELGE_TIPI = 0
	BEGIN
		IF @E_BELGE_AKTIF = 1
		BEGIN
			IF @TIP = 0
			BEGIN
				IF @BELGE_TURU = 0 SET @NUMERATOR_TURU = 22
				ELSE IF @BELGE_TURU = 1 SET @NUMERATOR_TURU = 26
			END
			ELSE BEGIN
				IF @BELGE_TURU = 0 SET @NUMERATOR_TURU = 23
				ELSE IF @BELGE_TURU = 1 SET @NUMERATOR_TURU = 25
				ELSE SET @NUMERATOR_TURU = 24
			END
		END
		ELSE 
			SET @NUMERATOR_TURU = CASE @TIP WHEN 0 THEN 22 ELSE 23 END
	END

	IF @NUMERATOR_TURU IS NOT NULL AND ISNULL(@FIS_NO,'') = ''
	BEGIN
		EXEC @DONUS_KODU = SODVZ_NUMERATOR_URET @NUMERATOR_TURU, @FIS_NO OUT, NULL, 1, @ONEK OUT, @ONUNE_SIFIR_KOY OUT
		IF @DONUS_KODU = 1
		BEGIN
			SET @HATA_MESAJI = 'Numeratör bitiş sayısını geçmiş'
			GOTO SON
		END
	END

	IF @YAZDIRILAN_BELGE_TIPI = 2 AND @E_BELGE_AKTIF = 1 AND @TIP = 1 AND @BELGE_TURU <> 0 AND @IRSALIYE_ZAMANI IS NOT NULL AND ISNULL(@IRSALIYE_NO,'') = ''
	BEGIN
		EXEC @DONUS_KODU = SODVZ_NUMERATOR_URET 27, @IRSALIYE_NO OUT, NULL, 1, @ONEK OUT, @ONUNE_SIFIR_KOY OUT
		IF @DONUS_KODU = 1
		BEGIN
			SET @HATA_MESAJI = 'İrsaliye numeratörü bitiş sayısını geçmiş'
			GOTO SON
		END
	END

	BEGIN TRAN

	-- Eski Kalemler Bakiye Düşüşü
	UPDATE B SET B.MIKTAR = B.MIKTAR - SX.MIKTAR
	FROM
		(SELECT SFS.URUN_ID, SF.VEZNE_ID, SUM(CASE WHEN SF.TIP = 0 THEN 1.0 ELSE -1.0 END * 
			CASE 
				-- 1. Altın (1) veya Gümüş (2) ise: kesinlikle MİKTAR (gram) vezneye işlenmeli
				WHEN ISNULL(SFS.URUN_TIPI, PR.URUN_TIPI) IN (1, 2)
				THEN SFS.MIKTAR

				-- 2. Ziynet (3) veya Döviz (0) ise: ADET çalışmalı
				WHEN ISNULL(SFS.URUN_TIPI, PR.URUN_TIPI) IN (0, 3)
				THEN CASE WHEN ISNULL(SFS.ADET, 0) > 0 THEN SFS.ADET ELSE (CASE WHEN ISNULL(SFS.MIKTAR, 0) > 0 THEN SFS.MIKTAR ELSE 1 END) END

				-- 3. Diğer
				ELSE SFS.MIKTAR
			END) AS MIKTAR
			FROM TODVZ_SARRAF_FISI SF
				INNER JOIN TODVZ_SARRAF_FISI_SATIRI SFS ON SF.SARRAF_FISI_ID = SFS.SARRAF_FISI_ID
				INNER JOIN TODVZ_PARA PR ON PR.PARA_ID = SFS.URUN_ID
			WHERE SF.SARRAF_FISI_ID = @SARRAF_FISI_ID
			GROUP BY SFS.URUN_ID, SF.VEZNE_ID
		) AS SX
		INNER JOIN TODVZ_VEZNE_BAKIYE B ON B.VEZNE_ID = SX.VEZNE_ID AND B.PARA_ID = SX.URUN_ID

	-- Eski Vezne Ödeme Satırları Bakiye Düşüşü
	UPDATE B SET B.MIKTAR = B.MIKTAR - SX.MIKTAR
	FROM
		(SELECT COALESCE(SFS.PARA_ID, 1) AS PARA_ID, SF.VEZNE_ID, SUM(CASE WHEN SF.TIP = 1 THEN 1.0 ELSE -1.0 END * SFS.MIKTAR) AS MIKTAR
			FROM TODVZ_SARRAF_FISI SF
				INNER JOIN TODVZ_ODEME_SATIRI SFS ON SF.SARRAF_FISI_ID = SFS.SARRAF_FISI_ID
				LEFT JOIN TODVZ_PARA PR_O ON PR_O.PARA_ID = COALESCE(SFS.PARA_ID, 1)
			WHERE SF.SARRAF_FISI_ID = @SARRAF_FISI_ID AND ISNULL(SFS.ODEME_ARACI_TURU, 0) = 0 AND SFS.ISLEME_YERI = 0
			GROUP BY COALESCE(SFS.PARA_ID, 1), SF.VEZNE_ID
		) AS SX
		INNER JOIN TODVZ_VEZNE_BAKIYE B ON B.VEZNE_ID = SX.VEZNE_ID AND B.PARA_ID = SX.PARA_ID

	IF (@SARRAF_FISI_ID IS NULL)
	BEGIN
		INSERT INTO TODVZ_SARRAF_FISI (
			VEZNE_ID, CARI_KART_ID, TARIH, SAAT, FIS_NO, TIP, ALTIN_HAS_KURU, KDV_ORANI, KDV,
			KISILIK_TIPI, UYRUK_ID, ULKE_ID, PASAPORT_NO, HUKUKI_YAPI_ID, VERGI_DAIRESI_ID,
			VERGI_KIMLIK_NO, BABA_ADI, ADRES, ILCE_ID, POSTA_KODU_ID, IL_ID, VEKIL_TURU,
			VEKIL_KISILIK_TIPI, VEKIL_ADI, VEKIL_KIMLIK_NO, EPOSTA, TELEFON_NO, MESLEK_ID,
			DOGUM_TARIHI, DOGUM_YERI, KIMLIK_SERI_NO, ANNE_ADI, MASAK_LISTESINDE_VAR,
			SUPHELI_ISLEMLER_YETKILI_ID, YETKILI_KISI_ID, SIRKET_TURU, KIMLIK_GECERLILIK_TARIHI,
			KIMLIK_BELGE_TURU, DERNEK_AMACI, YETKILI_KISI, E_FATURA_POSTA_KUTUSU, E_IRSALIYE_POSTA_KUTUSU,
			BELGE_TURU, IRSALIYE_ZAMANI, IRSALIYE_NO, SOFOR_ID, UNVAN, FAVORI_PARA_ID, ALIS_KURU,
			SATIS_KURU, GUMUS_HAS_KURU, E_FATURA_ETTN, E_IRSALIYE_ETTN, KAYITSIZ_MUSTERI_ID,
			EKLEYEN_ID, EKLEME_ZAMANI, GUNCELLEYEN_ID, GUNCELLEME_ZAMANI, GUID
		)
		VALUES (
			@VEZNE_ID, @CARI_KART_ID, @TARIH, @SAAT, @FIS_NO, @TIP, @ALTIN_HAS_KURU, @KDV_ORANI, @KDV,
			@KISILIK_TIPI, @UYRUK_ID, @ULKE_ID, @PASAPORT_NO, @HUKUKI_YAPI_ID, @VERGI_DAIRESI_ID,
			@VERGI_KIMLIK_NO, @BABA_ADI, @ADRES, @ILCE_ID, @POSTA_KODU_ID, @IL_ID, @VEKIL_TURU,
			@VEKIL_KISILIK_TIPI, @VEKIL_ADI, @VEKIL_KIMLIK_NO, @EPOSTA, @TELEFON_NO, @MESLEK_ID,
			@DOGUM_TARIHI, @DOGUM_YERI, @KIMLIK_SERI_NO, @ANNE_ADI, @MASAK_LISTESINDE_VAR,
			@SUPHELI_ISLEMLER_YETKILI_ID, @YETKILI_KISI_ID, @SIRKET_TURU, @KIMLIK_GECERLILIK_TARIHI,
			@KIMLIK_BELGE_TURU, @DERNEK_AMACI, @YETKILI_KISI, @E_FATURA_POSTA_KUTUSU, @E_IRSALIYE_POSTA_KUTUSU,
			@BELGE_TURU, @IRSALIYE_ZAMANI, @IRSALIYE_NO, @SOFOR_ID, @UNVAN, @FAVORI_PARA_ID, @ALIS_KURU,
			@SATIS_KURU, @GUMUS_HAS_KURU, NEWID(), NEWID(), @KAYITSIZ_MUSTERI_ID,
			@KULLANICI_ID, @SIMDIKI_ZAMAN, @KULLANICI_ID, @SIMDIKI_ZAMAN,
			CASE WHEN @GUID IS NOT NULL THEN @GUID ELSE NEWID() END
		)
		IF @@ERROR<>0
		BEGIN
			SET @HATA_MESAJI = 'Fiş kaydedilemedi'
			GOTO UNDO
		END
		SET @SARRAF_FISI_ID = @@IDENTITY
	END
	ELSE BEGIN
		DELETE OG
			FROM TODVZ_SARRAF_FISI_SATIRI S
				INNER JOIN TODVZ_URUN_OGESI_ISLEMI OG ON OG.SARRAF_FISI_SATIRI_ID = S.SARRAF_FISI_SATIRI_ID
			WHERE S.SARRAF_FISI_ID = @SARRAF_FISI_ID
		IF @@ERROR<>0
		BEGIN
			SET @HATA_MESAJI = 'Barkodlu ürün işlemleri silinemedi'
			GOTO UNDO
		END

		DELETE S
			FROM TODVZ_SARRAF_FISI_SATIRI S
				LEFT OUTER JOIN #TODVZ_ISKELE_SARRAF_FISI_SATIRI ISK ON ISK.SATIR_ID = S.SARRAF_FISI_SATIRI_ID
			WHERE S.SARRAF_FISI_ID = @SARRAF_FISI_ID AND ISK.SATIR_ID IS NULL
		IF @@ERROR<>0
		BEGIN
			SET @HATA_MESAJI = 'Fiş satırları silinemedi'
			GOTO UNDO
		END

		UPDATE TODVZ_SARRAF_FISI SET
				VEZNE_ID = @VEZNE_ID,
				CARI_KART_ID = @CARI_KART_ID,
				TARIH = @TARIH,
				SAAT = @SAAT,
				FIS_NO = @FIS_NO,
				TIP = @TIP,
				ALTIN_HAS_KURU = @ALTIN_HAS_KURU,
				KDV_ORANI = @KDV_ORANI,
				KDV = @KDV,
				KISILIK_TIPI = @KISILIK_TIPI,
				UYRUK_ID = @UYRUK_ID,
				ULKE_ID = @ULKE_ID,
				PASAPORT_NO = @PASAPORT_NO,
				HUKUKI_YAPI_ID = @HUKUKI_YAPI_ID,
				VERGI_DAIRESI_ID = @VERGI_DAIRESI_ID,
				VERGI_KIMLIK_NO = @VERGI_KIMLIK_NO,
				BABA_ADI = @BABA_ADI,
				ADRES = @ADRES,
				ILCE_ID = @ILCE_ID,
				POSTA_KODU_ID = @POSTA_KODU_ID,
				IL_ID = @IL_ID,
				VEKIL_TURU = @VEKIL_TURU,
				VEKIL_KISILIK_TIPI = @VEKIL_KISILIK_TIPI,
				VEKIL_ADI = @VEKIL_ADI,
				VEKIL_KIMLIK_NO = @VEKIL_KIMLIK_NO,
				EPOSTA = @EPOSTA,
				TELEFON_NO = @TELEFON_NO,
				MESLEK_ID = @MESLEK_ID,
				DOGUM_TARIHI = @DOGUM_TARIHI,
				DOGUM_YERI = @DOGUM_YERI,
				KIMLIK_SERI_NO = @KIMLIK_SERI_NO,
				ANNE_ADI = @ANNE_ADI,
				MASAK_LISTESINDE_VAR = @MASAK_LISTESINDE_VAR,
				YETKILI_KISI_ID = @YETKILI_KISI_ID,
				SIRKET_TURU = @SIRKET_TURU,
				KIMLIK_GECERLILIK_TARIHI = @KIMLIK_GECERLILIK_TARIHI,
				KIMLIK_BELGE_TURU = @KIMLIK_BELGE_TURU,
				DERNEK_AMACI = @DERNEK_AMACI,
				YETKILI_KISI = @YETKILI_KISI,
				E_FATURA_POSTA_KUTUSU = @E_FATURA_POSTA_KUTUSU,
				E_IRSALIYE_POSTA_KUTUSU = @E_IRSALIYE_POSTA_KUTUSU,
				BELGE_TURU = @BELGE_TURU,
				IRSALIYE_ZAMANI = @IRSALIYE_ZAMANI,
				IRSALIYE_NO = @IRSALIYE_NO,
				SOFOR_ID = @SOFOR_ID,
				UNVAN = @UNVAN,
				FAVORI_PARA_ID = @FAVORI_PARA_ID,
				ALIS_KURU = @ALIS_KURU,
				SATIS_KURU = @SATIS_KURU,
				GUMUS_HAS_KURU = @GUMUS_HAS_KURU,
				KAYITSIZ_MUSTERI_ID = @KAYITSIZ_MUSTERI_ID,
				GUNCELLEYEN_ID = @KULLANICI_ID,
				GUNCELLEME_ZAMANI = @SIMDIKI_ZAMAN
			WHERE SARRAF_FISI_ID = @SARRAF_FISI_ID
		IF @@ERROR<>0
		BEGIN
			SET @HATA_MESAJI = 'Fiş kaydedilemedi'
			GOTO UNDO
		END

		UPDATE S
			SET SATIR_NO = ISK.SATIR_NO,
			   URUN_ID = ISK.URUN_ID,
			   MIKTAR = ISK.MIKTAR,
			   MILYEM = ISK.MILYEM,
			   HAS_GRAM = ISK.HAS_GRAM,
			   ADET = ISK.ADET,
			   ISCILIK_MIKTARI = ISK.ISCILIK_MIKTARI,
			   ISCILIK_HAS_GRAM = ISK.ISCILIK_HAS_GRAM,
			   ACIKLAMA = ISK.ACIKLAMA,
			   ISCILIK_HESAPLAMA_SEKLI = ISK.ISCILIK_HESAPLAMA_SEKLI,
			   KUR = ISK.KUR,
			   TUTAR = ISK.TUTAR,
			   URUN_TIPI = ISK.URUN_TIPI,
			   URUN_OGESI_PARA_ID = ISK.URUN_OGESI_PARA_ID,
			   KARAT = ISK.KARAT
		FROM #TODVZ_ISKELE_SARRAF_FISI_SATIRI ISK
			INNER JOIN TODVZ_SARRAF_FISI_SATIRI S ON S.SARRAF_FISI_SATIRI_ID = ISK.SATIR_ID
		WHERE S.SARRAF_FISI_ID = @SARRAF_FISI_ID
		IF @@ERROR<>0
		BEGIN
			SET @HATA_MESAJI = 'Fiş satırları güncellemedi'
			GOTO UNDO
		END

		DELETE FROM TODVZ_ODEME_SATIRI WHERE SARRAF_FISI_ID = @SARRAF_FISI_ID
		IF @@ERROR<>0
		BEGIN
			SET @HATA_MESAJI = 'Ödeme satırları silinemedi'
			GOTO UNDO
		END
	END

	INSERT INTO TODVZ_SARRAF_FISI_SATIRI (
		SARRAF_FISI_ID, SATIR_NO, URUN_ID, MIKTAR, MILYEM, HAS_GRAM, ADET,
		ISCILIK_MIKTARI, ISCILIK_HAS_GRAM, ACIKLAMA, ISCILIK_HESAPLAMA_SEKLI,
		KUR, TUTAR, URUN_TIPI, URUN_OGESI_PARA_ID, KARAT
	)
	SELECT  
		@SARRAF_FISI_ID, SATIR_NO, URUN_ID, MIKTAR, MILYEM, HAS_GRAM, ADET,
		ISCILIK_MIKTARI, ISCILIK_HAS_GRAM, ACIKLAMA, ISCILIK_HESAPLAMA_SEKLI,
		KUR, TUTAR, URUN_TIPI, URUN_OGESI_PARA_ID, KARAT
	FROM #TODVZ_ISKELE_SARRAF_FISI_SATIRI
	WHERE SATIR_ID IS NULL
	IF @@ERROR<>0
	BEGIN
		SET @HATA_MESAJI = 'Fiş satırları kaydedilemedi'
		GOTO UNDO
	END

	-- ÖDEME SATIRLARINA CARI_KART_ID DE KAYDEDİLİR
	INSERT INTO TODVZ_ODEME_SATIRI (
		SARRAF_FISI_ID, SATIR_NO, ISLEME_YERI, ODEME_ARACI_TURU, PARA_ID,
		POS_CIHAZI_ID, MIKTAR, MILYEM, HAS_GRAM, KUR, TUTAR, DEGISTIRILDI,
		CARI_KART_ID
	)
	SELECT  
		@SARRAF_FISI_ID, SATIR_NO, ISLEME_YERI, ODEME_ARACI_TURU, PARA_ID,
		POS_CIHAZI_ID, MIKTAR, MILYEM, HAS_GRAM, KUR, TUTAR, DEGISTIRILDI,
		CARI_KART_ID
	FROM #TODVZ_ISKELE_ODEME_SATIRI
	IF @@ERROR<>0
	BEGIN
		SET @HATA_MESAJI = 'Ödeme satırları kaydedilemedi'
		GOTO UNDO
	END

	IF EXISTS(SELECT * FROM #TODVZ_ISKELE_URUN_OGESI_ISLEMI)
	BEGIN
		INSERT INTO TODVZ_URUN_OGESI_ISLEMI(SARRAF_FISI_SATIRI_ID, URUN_OGESI_ID, ADET, GRAMAJ, FIYAT)
			SELECT SFS.SARRAF_FISI_SATIRI_ID, ISK.URUN_OGESI_ID, ISK.ADET, ISK.GRAMAJ, ISK.FIYAT
				FROM TODVZ_SARRAF_FISI_SATIRI SFS
					INNER JOIN #TODVZ_ISKELE_URUN_OGESI_ISLEMI ISK ON ISK.SATIR_NO = SFS.SATIR_NO
				WHERE SFS.SARRAF_FISI_ID = @SARRAF_FISI_ID
		IF @@ERROR<>0
		BEGIN
			SET @HATA_MESAJI = 'Barkodlu ürün işlemleri kaydedilemedi'
			GOTO UNDO
		END
	END

	-- Yeni Kayıt Vezne Bakiye Güncellemesi
	IF @VEZNE_ID IS NOT NULL
	BEGIN
		INSERT INTO TODVZ_VEZNE_BAKIYE(VEZNE_ID, PARA_ID, MIKTAR)
			SELECT DISTINCT @VEZNE_ID, URUN_ID, 0.0
			FROM TODVZ_SARRAF_FISI_SATIRI
			WHERE SARRAF_FISI_ID = @SARRAF_FISI_ID AND URUN_ID IS NOT NULL AND URUN_ID NOT IN (SELECT PARA_ID FROM TODVZ_VEZNE_BAKIYE WHERE VEZNE_ID = @VEZNE_ID);

		UPDATE B SET B.MIKTAR = B.MIKTAR + SX.MIKTAR
		FROM
			(SELECT SFS.URUN_ID, SF.VEZNE_ID, SUM(CASE WHEN SF.TIP = 0 THEN 1.0 ELSE -1.0 END * 
				CASE 
				-- 1. Altın (1) veya Gümüş (2) ise: kesinlikle MİKTAR (gram) vezneye işlenmeli
				WHEN ISNULL(SFS.URUN_TIPI, PR.URUN_TIPI) IN (1, 2)
				THEN SFS.MIKTAR

				-- 2. Ziynet (3) veya Döviz (0) ise: ADET çalışmalı
				WHEN ISNULL(SFS.URUN_TIPI, PR.URUN_TIPI) IN (0, 3)
				THEN CASE WHEN ISNULL(SFS.ADET, 0) > 0 THEN SFS.ADET ELSE (CASE WHEN ISNULL(SFS.MIKTAR, 0) > 0 THEN SFS.MIKTAR ELSE 1 END) END

				-- 3. Diğer
				ELSE SFS.MIKTAR
			END) AS MIKTAR
				FROM TODVZ_SARRAF_FISI SF
					INNER JOIN TODVZ_SARRAF_FISI_SATIRI SFS ON SF.SARRAF_FISI_ID = SFS.SARRAF_FISI_ID
					INNER JOIN TODVZ_PARA PR ON PR.PARA_ID = SFS.URUN_ID
				WHERE SF.SARRAF_FISI_ID = @SARRAF_FISI_ID
				GROUP BY SFS.URUN_ID, SF.VEZNE_ID
			) AS SX
			INNER JOIN TODVZ_VEZNE_BAKIYE B ON B.VEZNE_ID = SX.VEZNE_ID AND B.PARA_ID = SX.URUN_ID;

		-- Sadece Nakit/Vezne (ODEME_ARACI_TURU = 0) olan ödeme satırları vezne nakit/altın bakiyesine eklenir
		INSERT INTO TODVZ_VEZNE_BAKIYE(VEZNE_ID, PARA_ID, MIKTAR)
			SELECT DISTINCT @VEZNE_ID, COALESCE(PARA_ID, 1), 0.0
			FROM TODVZ_ODEME_SATIRI
			WHERE SARRAF_FISI_ID = @SARRAF_FISI_ID AND ISNULL(ODEME_ARACI_TURU, 0) = 0 AND ISLEME_YERI = 0 
				AND COALESCE(PARA_ID, 1) NOT IN (SELECT PARA_ID FROM TODVZ_VEZNE_BAKIYE WHERE VEZNE_ID = @VEZNE_ID);

		UPDATE B SET B.MIKTAR = B.MIKTAR + SX.MIKTAR
		FROM
			(SELECT COALESCE(SFS.PARA_ID, 1) AS PARA_ID, SF.VEZNE_ID, SUM(CASE WHEN SF.TIP = 1 THEN 1.0 ELSE -1.0 END * SFS.MIKTAR) AS MIKTAR
				FROM TODVZ_SARRAF_FISI SF
					INNER JOIN TODVZ_ODEME_SATIRI SFS ON SF.SARRAF_FISI_ID = SFS.SARRAF_FISI_ID
					LEFT JOIN TODVZ_PARA PR_O ON PR_O.PARA_ID = COALESCE(SFS.PARA_ID, 1)
				WHERE SF.SARRAF_FISI_ID = @SARRAF_FISI_ID AND ISNULL(SFS.ODEME_ARACI_TURU, 0) = 0 AND SFS.ISLEME_YERI = 0
				GROUP BY COALESCE(SFS.PARA_ID, 1), SF.VEZNE_ID
			) AS SX
			INNER JOIN TODVZ_VEZNE_BAKIYE B ON B.VEZNE_ID = SX.VEZNE_ID AND B.PARA_ID = SX.PARA_ID;
	END

	COMMIT TRAN
	DELETE #TODVZ_ISKELE_SARRAF_FISI_SATIRI
	DELETE #TODVZ_ISKELE_URUN_OGESI_ISLEMI
	DELETE #TODVZ_ISKELE_ODEME_SATIRI
	RETURN 0

UNDO:
